function tokenPair(token) {
  const options = [token];
  for (let i = 0; i <= 2; i++)
    if (i === 0 || /^[وفبكل]+$/.test(token.slice(0, i))) {
      const t = token.slice(i);
      options.push(t, t.startsWith("ال") ? t.slice(2) : t);
    }
  for (const t of [...options])
    for (const suffix of ["ها", "هم", "نا", "كم", "كن", "ي", "ك", "ه"])
      if (t.endsWith(suffix)) options.push(t.slice(0, -suffix.length));
  for (const t of options) {
    const pair = index.get(t);
    if (pair) return pair;
  }
}
export function completeNounNumbers(items) {
  let changed = false;
  const result = items.map((k) => {
    const noun = k.vocabulary?.noun || {};
    const pairs = [...(noun.numberPairs || [])];
    const add = (p) => {
      if (
        !pairs.some(
          (x) =>
            norm(x.plural) === norm(p.plural) &&
            norm(x.singular) === norm(p.singular),
        )
      )
        pairs.push(p);
    };
    if (noun.singular)
      for (const p of noun.plurals || [])
        add({ singular: noun.singular, plural: p.arabic });
    const text = strings([
      k.arabic,
      k.collocations,
      k.examples?.map((e) => e.arabic),
      k.vocabulary?.phrases?.map((p) => p.arabic),
    ]).join(" ");
    for (const token of norm(text).split(/[\s،؛؟.!:()\[\]\/]+/)) {
      const p = tokenPair(token);
      if (p) add(p);
    }
    const alias = k.arabic
      .split(/\s*\/\s*/)
      .map((a) => norm(a).replace(/^ال/, ""));
    const own = pairs.find(
      (p) => alias.includes(norm(p.plural)) || alias.includes(norm(p.singular)),
    );
    const fillSingular = !noun.singular && own;
    const fillPlural = !noun.plurals?.length && own;
    if (
      pairs.length === (noun.numberPairs || []).length &&
      !fillSingular &&
      !fillPlural
    )
      return k;
    changed = true;
    return {
      ...k,
      vocabulary: {
        ...k.vocabulary,
        noun: {
          ...noun,
          ...(fillSingular ? { singular: own.singular } : {}),
          ...(fillPlural
            ? {
                plurals: pairs
                  .filter((p) => norm(p.singular) === norm(own.singular))
                  .map((p) => ({ arabic: p.plural, kind: "other" })),
              }
            : {}),
          ...(k.verb && noun.applicable === undefined
            ? {
                applicable: false,
                note:
                  noun.note || "本词为动词；单复数对应来自搭配或例句中的名词。",
              }
            : {}),
          numberPairs: pairs,
        },
      },
    };
  });
  return changed ? result : items;
}
